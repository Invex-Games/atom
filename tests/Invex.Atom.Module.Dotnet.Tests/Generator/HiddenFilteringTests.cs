namespace Invex.Atom.Module.Dotnet.Tests.Generator;

[TestFixture]
public class HiddenFilteringTests
{
    private const string Schema = """
                                  {
                                    "name": "dotnet",
                                    "subcommands": {
                                      "add": {
                                        "hidden": true,
                                        "subcommands": {
                                          "package": { "hidden": false, "description": "legacy add package" }
                                        }
                                      },
                                      "package": {
                                        "hidden": false,
                                        "subcommands": {
                                          "add": { "hidden": false, "description": "Add a NuGet package reference." }
                                        }
                                      },
                                      "complete": { "hidden": true },
                                      "internal-reportinstallsuccess": { "hidden": true },
                                      "help": { "hidden": false },
                                      "new": {
                                        "hidden": false,
                                        "options": {
                                          "--debug:attach": { "hidden": true, "valueType": "System.Boolean", "arity": { "minimum": 0, "maximum": 1 } },
                                          "--dry-run": { "hidden": false, "valueType": "System.Boolean", "arity": { "minimum": 0, "maximum": 1 } },
                                          "--force": { "hidden": false, "valueType": "System.Boolean", "arity": { "minimum": 0, "maximum": 0 } }
                                        },
                                        "subcommands": {
                                          "--show-alias": { "hidden": false },
                                          "alias": { "hidden": true, "subcommands": { "show": { "hidden": false } } }
                                        }
                                      },
                                      "build": {
                                        "hidden": false,
                                        "options": {
                                          "--property": { "hidden": true, "valueType": "System.Collections.ObjectModel.ReadOnlyDictionary<System.String, System.String>", "arity": { "minimum": 0 } },
                                          "--no-cache": { "hidden": true, "valueType": "System.Boolean", "arity": { "minimum": 0, "maximum": 0 } },
                                          "--nologo": { "hidden": false, "valueType": "System.Boolean", "arity": { "minimum": 0, "maximum": 0 } }
                                        }
                                      }
                                    }
                                  }
                                  """;

    private static IReadOnlyList<Command> GetCommands()
    {
        using var document = JsonDocument.Parse(Schema);
        var root = DotnetCliParser.GetCommand("dotnet", document.RootElement);
        root.ShouldNotBeNull();

        return DotnetCliGenerator.GetCommandsToGenerate(root);
    }

    [Test]
    public void HiddenCommands_AndTheirSubcommands_AreNotGenerated()
    {
        var names = GetCommands()
            .Select(x => x.Name)
            .ToList();

        names.ShouldBe(["package", "package add", "new", "build"]);
    }

    [Test]
    public void HiddenOptions_AreNotGenerated_UnlessRetained()
    {
        var commands = GetCommands();

        commands
            .Single(x => x.Name is "new")
            .Options
            .Select(x => x.Name)
            .ShouldBe(["--dry-run", "--force"]);

        commands
            .Single(x => x.Name is "build")
            .Options
            .Select(x => x.Name)
            .ShouldBe(["--property", "--nologo"]);
    }

    [Test]
    public void Parser_ReadsArity()
    {
        var newCommand = GetCommands()
            .Single(x => x.Name is "new");

        newCommand
            .Options
            .Single(x => x.Name is "--dry-run")
            .AcceptsValue
            .ShouldBeTrue();

        newCommand
            .Options
            .Single(x => x.Name is "--force")
            .AcceptsValue
            .ShouldBeFalse();
    }

    [Test]
    public void GeneratedFile_DoesNotContainHiddenOptions()
    {
        var newCommand = GetCommands()
            .Single(x => x.Name is "new");

        var code = DotnetCliGenerator.GenerateFile(newCommand);

        code.ShouldStartWith(DotnetCliGenerator.AutoGeneratedHeader);
        code.ShouldNotContain("debug", Case.Insensitive);
        code.ShouldContain("DryRun");
    }

    [Test]
    public void DuplicateCommandNames_Throw()
    {
        var root = new Command("dotnet",
            null,
            [],
            [],
            [
                new("tool-run", null, [], [], []),
                new("tool", null, [], [], [new("run", null, [], [], [])]),
            ]);

        Should.Throw<InvalidOperationException>(() => DotnetCliGenerator.GetCommandsToGenerate(root));
    }
}
